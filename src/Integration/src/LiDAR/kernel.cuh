typedef struct _OCTREE_POINT
{
    float32_t f32_X, f32_Y, f32_Z;

    __host__ __device__
    _OCTREE_POINT operator()(const _OCTREE_POINT &st_A, const _OCTREE_POINT &st_B) const 
    {
        return { st_A.f32_X + st_B.f32_X, st_A.f32_Y + st_B.f32_Y, st_A.f32_Z + st_B.f32_Z };
    }

    __host__ __device__
    _OCTREE_POINT operator+(const _OCTREE_POINT &st_Other) const 
    {
        return { f32_X + st_Other.f32_X, f32_Y + st_Other.f32_Y, f32_Z + st_Other.f32_Z };
    }

    __host__ __device__
    _OCTREE_POINT operator-(const _OCTREE_POINT& st_Other) const
    {
        return { f32_X - st_Other.f32_X, f32_Y - st_Other.f32_Y, f32_Z - st_Other.f32_Z };
    }

    __host__ __device__
    _OCTREE_POINT operator/(const int32_t &s32_Num) const
    {
        return { f32_X / s32_Num, f32_Y / s32_Num, f32_Z / s32_Num};
    }

